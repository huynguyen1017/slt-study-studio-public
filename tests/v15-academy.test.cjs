'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const {chromium}=require('playwright');
const ctx={window:{},console,localStorage:{getItem:()=>null}};
vm.runInNewContext(fs.readFileSync('simulation/virtual_academy.js','utf8'),ctx);
vm.runInNewContext(fs.readFileSync('simulation/academy_pins.js','utf8'),ctx);
vm.runInNewContext(fs.readFileSync('simulation/academy_ide.js','utf8'),ctx);
const m=ctx.window.virtualAcademyMath;
const d=m.calc(9,330,1000,470,220);
assert.ok(Math.abs(d.Rt-869.727891156)<1e-6,"TECH 60 expected resistance");
assert.ok(Math.abs(d.I*1000-10.348064137)<1e-6,"TECH 60 expected current");
assert.ok(Math.abs(d.kcl)<1e-12&&Math.abs(d.kvl)<1e-12);
const x=m.rc(4.5,150,1,150,"charge");
assert.ok(Math.abs(x.vc-4.5*(1-1/Math.E))<1e-8);
assert.equal(m.rc(4.5,150,1,150,"discharge").vc.toFixed(4),(4.5/Math.E).toFixed(4));
assert.equal(ctx.window.academyPinData["STM32 NUCLEO-L476RG"].some(p=>p[0]==="PA5"),true);
assert.equal(ctx.window.academyRtlSubset("module a; assign y = a & b; endmodule").vals[3][2],1);
assert.equal(ctx.window.academyStaticDiagnostics("int main(void){ return 0; }","c").length,0);
(async()=>{
 const browser=await chromium.launch({headless:true,args:["--no-sandbox"]});
 try{
  for(const width of [1280,390]){
   const page=await browser.newPage({viewport:{width,height:900},acceptDownloads:true});
   const errors=[];page.on("pageerror",err=>errors.push(err.message));
   await page.goto("http://127.0.0.1:8765/",{waitUntil:"domcontentloaded"});
   await page.locator('[data-mode="academy"]').click();
   assert.equal(await page.locator("#academyView").isVisible(),true);
   const t=await page.locator("#acaValues").textContent();
   assert.match(t,/869\.727891/);
   assert.match(await page.locator("#acaWireMessage").textContent(),/Connect remaining 6/);
   await page.locator("#acaAutoWire").click();
   assert.match(await page.locator("#acaWireMessage").textContent(),/PASS/);
   await page.locator("#acaPower").click();
   assert.match(await page.locator("#acaWireMessage").textContent(),/ON/);
   assert.match(await page.locator("#acaMeter").textContent(),/V/);
   await page.locator("#acaR2").fill("2000");
   await page.locator("#acaR2").press("Tab");
   assert.doesNotMatch(await page.locator("#acaValues").textContent(),/869\.727891/);
   assert.ok(await page.locator("#acaRcPlot svg").count()>0);
   await page.locator('[data-aca="pins"]').click();
   await page.locator("#acaBoard").selectOption("STM32 NUCLEO-L476RG");
   await page.locator("#acaPin").selectOption("PC13");
   await page.locator("#acaRole").selectOption("USER BUTTON");
   await page.locator("#acaAssign").click();
   assert.match(await page.locator("#acaAssigned").textContent(),/PC13/);
   assert.match(await page.locator("#acaPinGenerated").textContent(),/GPIO_PIN_13/);
   await page.locator("#acaSendIDE").click();
   assert.equal(await page.locator("#ideLang").inputValue(),"stm32");
   assert.match(await page.locator("#ideSource").inputValue(),/HAL_GPIO_ReadPin/);
   await page.locator("#ideLang").selectOption("verilog");
   await page.locator("#ideRun").click();
   assert.match(await page.locator("#ideOutput").textContent(),/4 binary truth-table combinations/);
   await page.locator("#ideLang").selectOption("c");
   await page.locator("#ideRun").click();
   assert.match(await page.locator("#ideOutput").textContent(),/NOT COMPILED/);
   await page.locator('[data-aca="report"]').click();
   assert.equal(await page.locator("#acaReport textarea").count(),7);
   await page.locator("#acaAppendData").click();
   assert.match(await page.locator("#acaReport").textContent(),/Calculated/);
   const dl=page.waitForEvent("download");
   await page.locator("#acaReportCsv").click();
   assert.equal((await dl).suggestedFilename(),"virtual-lab-report.md");
   await page.locator('[data-mode="cards"]').click();
   await page.locator("#flip").click();
   assert.ok(await page.locator(".notebook-classic .ink-question").count()>0);
   await page.locator('[data-note-page="1"]').click();
   assert.ok(await page.locator(".nb-typeset-equation math").count()>0,"MathML on Deep Dive equations");
   assert.deepEqual(errors,[],"no JavaScript runtime errors");
   console.log("PASS v15 at "+width+"px · resistor, RC, wiring, STM32 pins, IDE subset, report, MathML");
   await page.close();
  }
 }finally{await browser.close()}
})().catch(err=>{console.error(err);process.exitCode=1});
