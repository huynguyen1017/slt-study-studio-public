/* Surfer-style RTL/VCD inspection. Every signal in this panel comes from a
 * user-selected local file; the file never leaves the device. */
(function(){
const E=s=>String(s??"").replace(/[&<>"']/g,c=>({"&":"&amp;","<":"&lt;",">":"&gt;",'"':"&quot;","'":"&#39;"}[c]));
const C=["#76ee9f","#78b5ff","#ffd46c","#f38ab7","#9ad4fa","#e7abff","#83e0dc","#b9d991"];
const clamp=(x,a,b)=>Math.max(a,Math.min(b,x));
function parseVcd(source){
 const text=String(source||"");
 if(text.length>15*1024*1024)throw Error("VCD larger than 15 MB limit");
 const timescale=(text.match(/\$timescale\s+([\s\S]*?)\s*\$end/i)||[])[1]||"1ns";
 const match=timescale.match(/(\d+)\s*(fs|ps|ns|us|ms|s)/i);
 if(!match)throw Error("Unsupported VCD timescale");
 const units={fs:1e-6,ps:1e-3,ns:1,us:1000,ms:1e6,s:1e9};
 const tickNs=Number(match[1])*units[match[2].toLowerCase()];
 const vars=[],byCode=new Map(),scopes=[];let time=0,definitions=true,points=0;
 const lines=text.split(/\r?\n/);
 for(let line of lines){
  line=line.trim();if(!line)continue;
  if(line.startsWith("$scope")){const parts=line.split(/\s+/);scopes.push(parts[2]||"");continue}
  if(line.startsWith("$upscope")){scopes.pop();continue}
  if(line.startsWith("$var")){
   const m=line.match(/^\$var\s+\S+\s+(\d+)\s+(\S+)\s+(\S+)(.*?)\$end/);
   if(!m)continue;
   const width=Number(m[1]);if(width<1||width>4096)continue;
   const v={width,code:m[2],name:[...scopes,m[3]].filter(Boolean).join("."),range:m[4].trim(),data:[]};
   vars.push(v);if(!byCode.has(v.code))byCode.set(v.code,[]);
   byCode.get(v.code).push(v);continue;
  }
  if(line.startsWith("$enddefinitions")){definitions=false;continue}
  if(definitions||line.startsWith("$"))continue;
  if(line[0]==="#"){time=Number(line.slice(1))*tickNs;continue}
  let code=null,value=null;
  if(/^[01xXzZ]/.test(line)){value=line[0].toLowerCase();code=line.slice(1).trim();}
  else if(/^[bB]/.test(line)){
   const m=line.match(/^[bB]([01xXzZ]+)\s+(\S+)/);
   if(m){value=m[1].toLowerCase();code=m[2]}
  }
  if(!code||!byCode.has(code))continue;
  for(const v of byCode.get(code)){
   if(points>=300000)throw Error("Too many transitions: select a smaller VCD");
   const val=value.padStart(v.width,"0");
   if(v.data.length&&v.data[v.data.length-1][1]===val)continue;
   v.data.push([time,val]);points++;
  }
 }
 const usable=vars.filter(v=>v.data.length);
 if(!usable.length)throw Error("No scalar or vector transitions in this VCD");
 let duration=0;for(const v of usable){duration=Math.max(duration,v.data[v.data.length-1][0]);}
 return {signals:usable,duration:Math.max(tickNs,duration),tickNs,points};
}
function lookup(v,t){
 const a=v.data;if(!a.length)return"x";let lo=0,hi=a.length;
 while(lo<hi){const mid=(lo+hi)>>1;if(a[mid][0]<=t)lo=mid+1;else hi=mid}
 return lo?a[lo-1][1]:"x";
}
function fmt(v,raw,radix){
 if(!raw||/[xz]/.test(raw))return raw?.toUpperCase()||"X";
 if(radix==="bin")return raw.padStart(v.width,"0");
 const value=BigInt("0b"+raw);
 if(radix==="dec")return value.toString(10);
 if(radix==="signed"){
  const n=BigInt(v.width),signed=(value&(1n<<(n-1n)))?value-(1n<<n):value;
  return signed.toString(10);
 }
 return "0x"+value.toString(16).toUpperCase().padStart(Math.ceil(v.width/4),"0");
}
function markup(){
 return '<details class="rtl-vcd-shell" data-vcd-lab><summary>▤ RTL / ADDRESS BUS VIEWER · Surfer-style 0/1/X/Z + 8/16-bit vectors</summary>'+
 '<p>Import an authentic VCD generated by VCS, Icarus, Verilator or another HDL simulator. Select addresses, counters, BestDist, PEready, clock and data buses. All values come from the file; no fake bus transitions are created.</p>'+
 '<div class="rtl-vcd-bar"><label>Load local VCD <input id="rtlVcdFile" type="file" accept=".vcd,.txt"></label><label>Radix<select id="rtlVcdRadix"><option value="hex">Hex</option><option value="bin">Binary</option><option value="dec">Unsigned decimal</option><option value="signed">Signed decimal</option></select></label>'+
 '<button id="rtlVcdPlay" type="button">▶ Play A+B</button><button id="rtlVcdStop" type="button">■ Stop</button><button id="rtlVcdFit" type="button">Fit</button><button id="rtlVcdZoom" type="button">＋ Zoom</button><button id="rtlVcdBack" type="button">－ Zoom</button>'+
 '<button id="rtlVcdLink" type="button" aria-pressed="true">🔗 Link B: ON</button></div>'+
 '<div id="rtlVcdNotice" role="status" aria-live="polite">No trace loaded. Use a VCD file from your own simulation; screenshots alone cannot provide time-indexed signal data.</div>'+
 '<div id="rtlVcdPicker" class="rtl-vcd-picker" hidden></div>'+
 '<div class="rtl-vcd-viewport" tabindex="0" role="region" aria-label="Scrollable digital timing diagram"><svg id="rtlVcdSvg" class="rtl-vcd-svg" viewBox="0 0 1120 550" role="img" aria-label="Digital timing bus lanes with synchronized A and B markers" tabindex="0"></svg></div>'+
 '<div id="rtlVcdAB" class="rtl-vcd-ab"></div>'+
 '<p class="rtl-vcd-note">All parsing is local to your browser; nothing is uploaded or added to this public repository. X and Z are preserved. Unlike the analog SPICE panels, these are RTL logic values, not measured voltage.</p></details>';
}
function mount(host){
 if(!host)return;
 const $=q=>host.querySelector(q);
 let data=null,selection=[],a=0,b=0,gap=0,linked=true,left=0,right=1,raf=0,playing=false,radix="hex";
 function stop(){playing=false;cancelAnimationFrame(raf);raf=0}
 function sync(){if(linked&&data)b=clamp(a+gap,0,data.duration)}
 function chooseDefaults(){
  const order=[/clock|clk/i,/count|addr/i,/bestdist|accumulate|sad/i,/ready|newbest|motion|complete/i];
  const ranked=[...data.signals].sort((x,y)=>{
   const rank=z=>{const n=order.findIndex(r=>r.test(z.name));return n<0?20:n};
   return rank(x)-rank(y);
  });
  selection=ranked.slice(0,Math.min(4,ranked.length));
  $("#rtlVcdPicker").hidden=false;
  $("#rtlVcdPicker").innerHTML='<div class="rtl-vcd-picker-title">Choose up to 8 real VCD signal lanes</div>'+
   data.signals.slice(0,120).map((v,i)=>'<label><input type="checkbox" data-vcd-signal="'+i+'" '+(selection.includes(v)?"checked":"")+'><span>'+E(v.name)+(v.width>1?' ['+v.width+' bits]':'')+'</span></label>').join("");
  $("#rtlVcdPicker").onchange=e=>{
   const idx=e.target.dataset.vcdSignal;if(idx===undefined)return;
   const v=data.signals[+idx];
   if(e.target.checked){if(selection.length>=8){e.target.checked=false;return}selection.push(v)}
   else selection=selection.filter(x=>x!==v);
   paint();
  };
 }
 function paint(){
  if(!data){$("#rtlVcdSvg").innerHTML='<text x="45" y="70" fill="#b6cfeb" font-size="16">Open a VCD file to inspect real 0 / 1 / X / Z and hexadecimal address values.</text>';return}
  const s=data.signals,T=data.duration,W=1120,sx=250,ex=1090,lo=left,hi=right,span=Math.max(1e-12,hi-lo);
  const X=t=>sx+(t-lo)/span*(ex-sx);
  let svg='<rect width="1120" height="550" fill="#081323"/>';
  for(let k=0;k<=10;k++){
   const time=lo+span*k/10,x=X(time);
   svg+='<path d="M'+x+' 34 V495" stroke="#203b54"/><text x="'+x+'" y="526" fill="#bdd8ee" text-anchor="middle" font-size="11">'+time.toFixed(span<2?3:1)+'</text>';
  }
  const lx=clamp(X(Math.min(a,b)),sx,ex),rx=clamp(X(Math.max(a,b)),sx,ex);
  svg+='<rect x="'+lx+'" y="34" width="'+Math.max(0,rx-lx)+'" height="460" fill="#66e5c3" fill-opacity=".09"/>';
  selection.forEach((v,j)=>{
   const y=48+j*55,high=y+5,low=y+32,col=C[j%C.length];
   svg+='<rect x="6" y="'+(y-9)+'" width="1108" height="52" rx="5" fill="'+(j%2?"#0e2032":"#0b1c2d")+'"/>'+
    '<text x="12" y="'+(y+11)+'" fill="'+col+'" font-size="13" font-weight="750">'+E(v.name.slice(0,31))+'</text>'+
    '<text x="12" y="'+(y+29)+'" fill="#9ab8ce" font-size="11">'+v.width+' bit'+(v.width===1?'':'s')+'</text>';
   const ev=v.data.filter(r=>r[0]>=lo&&r[0]<=hi);
   const prev=lookup(v,lo),drawEv=[[lo,prev],...ev.filter(r=>r[0]>lo)].slice(0,1300);
   drawEv.forEach((ev,i)=>{
    const x0=X(ev[0]),x1=X(drawEv[i+1]?.[0]??hi);
    const value=ev[1],tag=fmt(v,value,radix);
    if(v.width===1){
     const yy=value==="1"?high:value==="0"?low:y+19;
     svg+='<path d="M'+x0+' '+yy+' H'+x1+'" stroke="'+(value==="x"?"#f67b7b":value==="z"?"#e2ba73":col)+'" stroke-width="2.5"/>';
     if(i&&x0>sx)svg+='<path d="M'+x0+' '+high+' V'+low+'" stroke="'+col+'" opacity=".8"/>';
     if(x1-x0>18)svg+='<text x="'+((x0+x1)/2)+'" y="'+(value==="1"?high-5:low+12)+'" fill="'+col+'" font-size="11" text-anchor="middle">'+value.toUpperCase()+'</text>';
    }else if(x1>x0){
     const q=Math.min(5,(x1-x0)/4);
     svg+='<path d="M'+(x0+q)+' '+high+' H'+(x1-q)+' L'+x1+' '+(y+19)+' L'+(x1-q)+' '+low+' H'+(x0+q)+' L'+x0+' '+(y+19)+' Z" stroke="'+col+'" fill="'+col+'" fill-opacity=".07"/>';
     if(x1-x0>Math.min(36,tag.length*6.2+6))svg+='<text x="'+((x0+x1)/2)+'" y="'+(y+23)+'" text-anchor="middle" fill="'+col+'" font-size="10.5">'+E(tag.length>18?tag.slice(0,17)+"…":tag)+'</text>';
    }
   });
   [[a,"A","#ffd57b"],[b,"B","#68e6c4"]].forEach(([t,mark,c])=>{
    if(t<lo||t>hi)return;
    const v0=lookup(v,t),yy=v.width>1?y+19:v0==="1"?high:v0==="0"?low:y+19;
    svg+='<circle data-vcd-marker="'+mark+'" data-lane="'+j+'" cx="'+X(t)+'" cy="'+yy+'" r="4.6" fill="'+c+'" stroke="#071627" stroke-width="1.5"/>';
   });
  });
  [[a,"A","#ffd57b"],[b,"B","#68e6c4"]].forEach(([t,n,c])=>{
   if(t<lo||t>hi)return;
   const x=X(t);
   svg+='<path d="M'+x+' 26 V495" stroke="'+c+'" stroke-dasharray="6 5" stroke-width="1.8"/>'+
    '<rect x="'+clamp(x-20,sx,ex-40)+'" y="3" width="40" height="22" rx="5" fill="#263950" stroke="'+c+'"/>'+
    '<text x="'+clamp(x,sx+20,ex-20)+'" y="19" fill="'+c+'" font-size="13" font-weight="bold" text-anchor="middle">'+n+'</text>';
  });
  svg+='<text x="1085" y="545" fill="#afc5dc" text-anchor="end" font-size="12">TIME (ns) · imported VCD event timestamps</text>';
  $("#rtlVcdSvg").innerHTML=svg;
  $("#rtlVcdAB").innerHTML='<strong>A: '+a.toFixed(3)+' ns · B: '+b.toFixed(3)+' ns · Δt: '+(b-a).toFixed(3)+' ns</strong><div class="rtl-vcd-matrix"><table><thead><tr><th>RTL signal</th><th>@ A</th><th>@ B</th></tr></thead><tbody>'+
   selection.map((v,j)=>'<tr><th style="color:'+C[j%C.length]+'">'+E(v.name)+'</th><td>'+E(fmt(v,lookup(v,a),radix))+'</td><td>'+E(fmt(v,lookup(v,b),radix))+'</td></tr>').join("")+'</tbody></table></div>';
 }
 $("#rtlVcdFile").onchange=async e=>{
  const file=e.target.files?.[0];if(!file)return;stop();
  try{
   if(file.size>15*1024*1024)throw Error("File larger than 15 MB");
   data=parseVcd(await file.text());left=0;right=data.duration;a=0;gap=Math.min(data.duration*.2,data.duration);b=gap;linked=true;
   chooseDefaults();$("#rtlVcdNotice").textContent="Loaded "+file.name+" · "+data.signals.length+" signals · "+data.points+" source transitions · "+data.duration.toFixed(3)+" ns span. Values come from this local file.";
   paint();
  }catch(err){data=null;$("#rtlVcdNotice").textContent="VCD import failed: "+err.message;paint()}
 };
 $("#rtlVcdRadix").onchange=e=>{radix=e.target.value;paint()};
 $("#rtlVcdLink").onclick=()=>{linked=!linked;gap=b-a;$("#rtlVcdLink").setAttribute("aria-pressed",String(linked));$("#rtlVcdLink").textContent=linked?"🔗 Link B: ON":"Unlink B: OFF";paint()};
 $("#rtlVcdStop").onclick=stop;
 $("#rtlVcdFit").onclick=()=>{if(!data)return;left=0;right=data.duration;paint()};
 $("#rtlVcdZoom").onclick=()=>{if(!data)return;const width=(right-left)*.5,mid=(left+right)*.5;left=clamp(mid-width*.5,0,data.duration-width);right=left+width;paint()};
 $("#rtlVcdBack").onclick=()=>{if(!data)return;const width=Math.min(data.duration,(right-left)*2),mid=(left+right)*.5;left=clamp(mid-width*.5,0,data.duration-width);right=left+width;paint()};
 $("#rtlVcdPlay").onclick=()=>{
  if(!data)return;stop();playing=true;a=0;sync();
  const start=performance.now();
  const frame=now=>{if(!playing)return;a=clamp((now-start)/8000*data.duration,0,data.duration);sync();paint();
   if(a>=data.duration){stop();return}raf=requestAnimationFrame(frame)};
  raf=requestAnimationFrame(frame);
 };
 $("#rtlVcdSvg").onpointerdown=e=>{
  if(!data)return;stop();
  const rect=e.currentTarget.getBoundingClientRect(),px=(e.clientX-rect.left)/rect.width*1120;
  if(px<250||px>1090)return;
  const t=clamp(left+(px-250)/840*(right-left),0,data.duration);
  const bPx=250+(b-left)/(right-left)*840;
  if(Math.abs(px-bPx)<16){b=t;gap=b-a;}else{a=t;sync()}
  paint();
 };
 paint();
}
window.parseLocalVcd=parseVcd;
window.renderDigitalVcdLab=markup;
window.mountDigitalVcdLab=mount;
})();